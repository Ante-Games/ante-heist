// Testnet CLI. Everything runs from ONE funded testnet account you create yourself.
//
//   OWNER_ACCOUNT_ID=you.testnet OWNER_PRIVATE_KEY=ed25519:... npm run testnet -- setup
//       creates heist./settler./scout./cryptographer./operator./player.<you>, deploys and
//       initialises the contract, funds mission-1, and writes .env.testnet (keys + secret).
//   npm run start:testnet                 run the game server against testnet (another terminal)
//   npm run testnet -- play [hire|solo]    scripted lead paying real testnet NEAR
//   npm run testnet -- status              mission and contract state
//   npm run testnet -- reveal              reveal the secret, closing the mission
import { writeFileSync, existsSync } from 'node:fs';
import { setupMission, playOnChain, near, TGAS } from './near-ops.ts';

const RPC = process.env.NEAR_RPC_URL ?? 'https://rpc.testnet.near.org';
const ENV_FILE = '.env.testnet';

function need(name: string): string {
  const v = process.env[name];
  if (!v) { console.error(`missing ${name}`); process.exit(1); }
  return v;
}

const [cmd, arg] = process.argv.slice(2);

if (cmd === 'setup') {
  if (existsSync(ENV_FILE)) { console.error(`${ENV_FILE} already exists; delete it to set up again`); process.exit(1); }
  const env = await setupMission({ rpcUrl: RPC, ownerId: need('OWNER_ACCOUNT_ID'), ownerKey: need('OWNER_PRIVATE_KEY'), potNear: process.env.POT_NEAR });
  const lines = ['# Generated by scripts/testnet.ts setup. Contains private keys: never commit.', ...Object.entries(env).map(([k, v]) => `${k}=${v}`), ''];
  writeFileSync(ENV_FILE, lines.join('\n'), { mode: 0o600 });
  console.log(`wrote ${ENV_FILE}. Next: npm run start:testnet (in another terminal), then npm run testnet -- play hire`);
} else if (cmd === 'play') {
  const style = arg === 'solo' ? 'solo' : arg === 'reckless' ? 'reckless' : 'hire';
  const r = await playOnChain({
    rpcUrl: RPC, base: process.env.HEIST_URL ?? `http://localhost:${process.env.PORT ?? 8787}`,
    contractId: need('HEIST_CONTRACT_ID'), missionId: need('HEIST_MISSION_ID'), playerId: need('PLAYER_ACCOUNT_ID'), playerKey: need('PLAYER_PRIVATE_KEY'), style,
  });
  console.log(r.transcript.log.filter((e) => e.kind === 'settle').map((e) => e.detail).join('\n'));
  console.log(`on chain run ${r.runId}: ${JSON.stringify(r.run)}`);
} else if (cmd === 'status') {
  const n = near(RPC);
  const c = need('HEIST_CONTRACT_ID');
  console.log('mission', JSON.stringify(await n.view(c, 'get_mission', { mission_id: need('HEIST_MISSION_ID') }), null, 2));
  console.log('runs', await n.view(c, 'run_count'));
  for (const npc of ['Scout', 'Cryptographer', 'Operator']) console.log(npc, JSON.stringify(await n.view(c, 'get_npc', { npc })));
} else if (cmd === 'reveal') {
  const n = near(RPC);
  const settler = n.account(need('SETTLER_ACCOUNT_ID'), need('SETTLER_PRIVATE_KEY'));
  await settler.callFunction({ contractId: need('HEIST_CONTRACT_ID'), methodName: 'reveal_secret', gas: TGAS(30), args: { mission_id: need('HEIST_MISSION_ID'), secret: need('HEIST_MISSION_SECRET') } });
  console.log('secret revealed; mission closed. The sponsor can now call withdraw_pot.');
} else {
  console.log('usage: npm run testnet -- setup | play [hire|solo|reckless] | status | reveal');
}

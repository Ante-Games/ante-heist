// Testnet helper. Everything runs from ONE funded testnet account you create yourself.
//
//   OWNER_ACCOUNT_ID=you.testnet OWNER_PRIVATE_KEY=ed25519:... node scripts/testnet.ts setup
//       creates heist./settler./scout./cryptographer./operator./player.<you>, deploys and
//       initialises the contract, funds mission-1, and writes .env.testnet (keys + secret).
//   npm run start:testnet                      run the game server against testnet
//   node --env-file=.env.testnet scripts/testnet.ts play [solo|hire]   scripted lead, paying real testnet NEAR
//   node --env-file=.env.testnet scripts/testnet.ts status             mission and contract state
//   node --env-file=.env.testnet scripts/testnet.ts reveal             reveal the secret, closing the mission
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { Account, JsonRpcProvider, KeyPair, nearToYocto } from 'near-api-js';
import { sha256Hex } from '../game/src/heist.ts';
import { playScripted } from '../game/lead/scripted.ts';

const RPC = process.env.NEAR_RPC_URL ?? 'https://rpc.testnet.near.org';
const WASM = 'contract/target/near/ante_heist_contract.wasm';
const ENV_FILE = '.env.testnet';
const provider = new JsonRpcProvider({ url: RPC });
const TGAS = (n: number) => BigInt(n) * 10n ** 12n;

function need(name: string): string {
  const v = process.env[name];
  if (!v) { console.error(`missing ${name}`); process.exit(1); }
  return v;
}

function account(id: string, key: string) {
  return new Account(id, provider, key as `ed25519:${string}`);
}

async function exists(id: string): Promise<boolean> {
  try { await provider.viewAccount({ accountId: id }); return true; } catch { return false; }
}

async function setup() {
  const ownerId = need('OWNER_ACCOUNT_ID');
  const owner = account(ownerId, need('OWNER_PRIVATE_KEY'));
  if (existsSync(ENV_FILE)) { console.error(`${ENV_FILE} already exists; delete it to set up again`); process.exit(1); }
  if (!existsSync(WASM)) { console.error(`build the contract first: cd contract && cargo near build non-reproducible-wasm`); process.exit(1); }

  const fund = {
    heist: process.env.CONTRACT_NEAR ?? '2',
    settler: '0.5',
    scout: '0.1',
    cryptographer: '0.1',
    operator: '0.1',
    player: process.env.PLAYER_NEAR ?? '1.5',
  };
  const keys: Record<string, string> = {};
  for (const [prefix, near] of Object.entries(fund)) {
    const id = `${prefix}.${ownerId}`;
    if (await exists(id)) { console.error(`${id} already exists; pick another owner account or delete it`); process.exit(1); }
    const kp = KeyPair.fromRandom('ed25519');
    await owner.createSubAccount({ accountOrPrefix: id, publicKey: kp.getPublicKey(), nearToTransfer: nearToYocto(near) });
    keys[prefix] = kp.toString();
    console.log(`created ${id} (${near} NEAR)`);
  }

  const contractId = `heist.${ownerId}`;
  const contract = account(contractId, keys.heist);
  await contract.deployContract(new Uint8Array(readFileSync(WASM)));
  await contract.callFunction({
    contractId, methodName: 'new', gas: TGAS(50),
    args: { owner: ownerId, settler: `settler.${ownerId}`, scout: `scout.${ownerId}`, cryptographer: `cryptographer.${ownerId}`, operator: `operator.${ownerId}` },
  });
  console.log(`deployed and initialised ${contractId}`);

  const secret = randomBytes(32).toString('hex');
  const missionId = 'mission-1';
  const pot = process.env.POT_NEAR ?? '2';
  await owner.callFunction({
    contractId, methodName: 'fund_mission', gas: TGAS(30), deposit: nearToYocto(pot),
    args: { mission_id: missionId, seed_hash: sha256Hex(secret), reward: nearToYocto('1').toString() },
  });
  console.log(`funded ${missionId}: pot ${pot} NEAR, reward 1 NEAR, commitment ${sha256Hex(secret)}`);

  writeFileSync(ENV_FILE, [
    '# Generated by scripts/testnet.ts setup. Contains private keys: never commit.',
    'HEIST_CHAIN=testnet',
    `NEAR_RPC_URL=${RPC}`,
    `HEIST_CONTRACT_ID=${contractId}`,
    `HEIST_MISSION_ID=${missionId}`,
    `HEIST_MISSION_SECRET=${secret}`,
    `SETTLER_ACCOUNT_ID=settler.${ownerId}`,
    `SETTLER_PRIVATE_KEY=${keys.settler}`,
    `OWNER_ACCOUNT_ID=${ownerId}`,
    `PLAYER_ACCOUNT_ID=player.${ownerId}`,
    `PLAYER_PRIVATE_KEY=${keys.player}`,
    `SCOUT_PRIVATE_KEY=${keys.scout}`,
    `CRYPTOGRAPHER_PRIVATE_KEY=${keys.cryptographer}`,
    `OPERATOR_PRIVATE_KEY=${keys.operator}`,
    `HEIST_CONTRACT_PRIVATE_KEY=${keys.heist}`,
    '',
  ].join('\n'), { mode: 0o600 });
  console.log(`wrote ${ENV_FILE}. Next: npm run start:testnet, then npm run testnet -- play hire`);
}

async function play(style: 'solo' | 'hire') {
  const contractId = need('HEIST_CONTRACT_ID');
  const playerId = need('PLAYER_ACCOUNT_ID');
  const player = account(playerId, need('PLAYER_PRIVATE_KEY'));
  const base = process.env.HEIST_URL ?? `http://localhost:${process.env.PORT ?? 8787}`;
  const runId = await player.callFunction<number>({
    contractId, methodName: 'start_run', gas: TGAS(30), deposit: nearToYocto('0.01'),
    args: { mission_id: need('HEIST_MISSION_ID') },
  });
  console.log(`start_run → run_id ${runId}`);
  const price: Record<string, string> = { scout: '0.1', cryptographer: '0.1', operator: '0.2' };
  const name: Record<string, string> = { scout: 'Scout', cryptographer: 'Cryptographer', operator: 'Operator' };
  const pay = async (npc: 'scout' | 'cryptographer' | 'operator') => {
    const hireIndex = await player.callFunction<number>({
      contractId, methodName: 'hire', gas: TGAS(30), deposit: nearToYocto(price[npc]),
      args: { run_id: runId, npc: name[npc] },
    });
    console.log(`  on chain: hire(${name[npc]}) paid ${price[npc]} NEAR → hire #${hireIndex}`);
    return { hireIndex };
  };
  const { transcript } = await playScripted({ base, style, pay, start: { player: playerId, chainRunId: String(runId) }, log: console.log });
  const t = transcript as { log: { kind: string; detail?: string }[] };
  console.log(t.log.filter((e) => e.kind === 'settle').map((e) => e.detail).join('\n'));
  console.log(`on chain run: ${JSON.stringify(await view(contractId, 'get_run', { run_id: runId }))}`);
}

async function view(contractId: string, method: string, args: Record<string, unknown>) {
  return provider.callFunction({ contractId, method, args });
}

async function status() {
  const contractId = need('HEIST_CONTRACT_ID');
  console.log('mission', JSON.stringify(await view(contractId, 'get_mission', { mission_id: need('HEIST_MISSION_ID') }), null, 2));
  console.log('runs', await view(contractId, 'run_count', {}));
  for (const npc of ['Scout', 'Cryptographer', 'Operator']) console.log(npc, JSON.stringify(await view(contractId, 'get_npc', { npc })));
}

async function reveal() {
  const contractId = need('HEIST_CONTRACT_ID');
  const settler = account(need('SETTLER_ACCOUNT_ID'), need('SETTLER_PRIVATE_KEY'));
  await settler.callFunction({ contractId, methodName: 'reveal_secret', gas: TGAS(30), args: { mission_id: need('HEIST_MISSION_ID'), secret: need('HEIST_MISSION_SECRET') } });
  console.log('secret revealed; mission closed. The sponsor can now call withdraw_pot.');
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === 'setup') await setup();
else if (cmd === 'play') await play(arg === 'solo' ? 'solo' : 'hire');
else if (cmd === 'status') await status();
else if (cmd === 'reveal') await reveal();
else console.log('usage: node scripts/testnet.ts setup | play [solo|hire] | status | reveal');
